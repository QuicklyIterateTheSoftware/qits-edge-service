package eu.wohlben.qits.edge;

import static io.restassured.RestAssured.given;

import eu.wohlben.qits.edge.contracts.GoldenFiles;
import io.quarkus.test.common.WithTestResource;
import io.quarkus.test.junit.QuarkusTest;
import java.util.regex.Pattern;
import org.junit.jupiter.api.Test;

/**
 * Pins {@code docs/openapi.yml} to the document this build serves at {@code /q/openapi}
 * (qits-1926), the way qits-githost-service pins its own. The platform's coverage check matches the
 * golden masters' operations against the committed file, so an operation added or renamed is a
 * reviewable diff here before it is a coverage gap there.
 *
 * <p>The document is {@code META-INF/openapi.yaml} and nothing else — the edge's routes are Vert.x,
 * so nothing is scanned — and it is served in dev and test only: the edge answers {@code /q/*} on
 * every Host, so in production it would be an anonymous route on every vhost. {@code EdgeRouter}
 * hands {@code /q/*} on to Quarkus whatever the Host, which is why the plain request below reaches
 * it.
 *
 * <p>It compares by default and fails with a unified diff when the served document moved; {@code
 * -Dgolden.update=true} (or {@code QITS_GOLDEN_UPDATE=true}) rewrites the file. {@code
 * info.version} is the release version, so it is written as a placeholder: a release alone moves
 * neither the comparison nor the file.
 *
 * <p>{@link StubGateways}, as {@code EdgeRoutingTest} has it: the same test resources mean the same
 * Quarkus start, and a second start in this JVM breaks the WebSocket tests of whichever class runs
 * after it (see the surefire executions in {@code service/pom.xml}).
 */
@QuarkusTest
@WithTestResource(StubGateways.class)
public class OpenApiSchemaExportTest {

  /** The one two-space-indented {@code version:} key in the document is {@code info.version}. */
  private static final Pattern INFO_VERSION = Pattern.compile("(?m)^  version: .*$");

  @Test
  public void exportOpenApiSchema() {
    String schema = given().when().get("/q/openapi").then().statusCode(200).extract().asString();

    String header =
        "# THIS FILE IS GENERATED BY OpenApiSchemaExportTest — DO NOT EDIT MANUALLY.\n"
            + "# Run `./mvnw -pl service -am test -Dtest=OpenApiSchemaExportTest"
            + " -Dsurefire.failIfNoSpecifiedTests=false -Dgolden.update=true` to regenerate.\n";

    GoldenFiles.compareOrWrite(
        GoldenFiles.repositoryRoot().resolve("docs").resolve("openapi.yml"),
        INFO_VERSION.matcher(header + schema).replaceAll("  version: <release version>"));
  }
}
